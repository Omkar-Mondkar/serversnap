#!/usr/bin/env python3
"""
serve_dashboard.py
====================


Publishes the HTML dashboard(s) generated by visualize_report.py over plain
HTTP, so they can be opened from a browser at http://<server>:<port>/ instead
of copying files around manually.


Design goals (matching server_snapshot.py / visualize_report.py):
  - Stdlib only (http.server), no external dependencies.
  - Long-running foreground process, intended to be supervised by cron
    (@reboot) or nohup/Control-M - NOT a systemd unit, per deployment
    constraints. See README.md for examples.
  - Serves ONLY the dedicated report_dir/dashboard/ folder written by
    visualize_report.py (or an explicit --dir), never the raw reports/ or
    snapshots/ directories. Directory listing is disabled and any request
    for a non-.html path is rejected, so this cannot be used to browse or
    exfiltrate arbitrary files even if something else ends up in that
    folder.
  - "/" redirects to latest_dashboard_<server_id>.html, which
    visualize_report.py refreshes in place on every run - so the URL never
    changes even as new dashboards are generated by cron.
  - Provides a JSON API at /api/config for reading and writing
    config.json from the dashboard UI (CRUD operations). Each write
    creates a timestamped backup of the previous config.


SECURITY WARNING - read before exposing beyond localhost:
  This server speaks plain HTTP with NO authentication and NO TLS. The
  dashboard can embed full file content and diffs of monitored files
  (which may include secrets, credentials, etc. if include_content is
  enabled in config.json). Anyone who can reach the port can read that
  data. Because of this:
    - The default host is 127.0.0.1 (localhost only) unless overridden by
      "dashboard.host" in config.json or --host. Reach localhost-only
      remotely via an SSH tunnel instead of exposing it on the network:
          ssh -L 8080:127.0.0.1:8080 user@<server>
          then open http://127.0.0.1:8080/ on your own machine.
    - Set "dashboard.host" in config.json (or pass --host) to the server's
      real IP, or 0.0.0.0, to serve http://<server-ip>:<port>/ directly on
      the network - only do this if you understand the exposure, and pair
      it with host firewall rules (firewalld/iptables) restricting the
      port to trusted source IPs.
    - Never expose this port to the open internet.


Usage:
  # Serve report_dir/dashboard/ (from config.json) - binds to
  # dashboard.host/dashboard.port in config.json if set, else
  # 127.0.0.1:8080 (access via an SSH tunnel):
  serve_dashboard.py --config /else/server_snapshot/config/config.json


  # Explicit directory + server_id (no config.json needed):
  serve_dashboard.py --dir /else/server_snapshot/reports/dashboard \\
      --server-id web01 --port 8080


  # Serve directly on the network at http://<server-ip>:<port>/ (CLI flags
  # always override config.json's dashboard.host/dashboard.port):
  serve_dashboard.py --config ... --host 10.80.22.204 --port 8080


Keeping it running without systemd (examples, see README.md for more):
  nohup python3 /else/server_snapshot/bin/serve_dashboard.py \\
      --config /else/server_snapshot/config/config.json --port 8080 \\
      >> /else/server_snapshot/logs/serve_dashboard.log 2>&1 &


  # restart automatically after a reboot, via crontab -e:
  @reboot nohup python3 /else/server_snapshot/bin/serve_dashboard.py --config /else/server_snapshot/config/config.json --port 8080 >> /else/server_snapshot/logs/serve_dashboard.log 2>&1 &


Exit codes:
  0 - clean shutdown (SIGINT/SIGTERM)
  2 - fatal error (bad arguments, directory not found, port already in use)
"""


from __future__ import annotations


import argparse
import functools
import http.server
import json
import os
import shutil
import signal
import sys
import threading
from datetime import datetime, timezone
from typing import Any, Dict, Optional


DEFAULT_CONFIG_PATH = "/else/server_snapshot/config/config.json"
SCRIPT_VERSION = "1.1.0"




class ServeDashboardError(Exception):
    """Raised for any fatal problem starting the server."""




def load_minimal_config(config_path: str) -> Dict[str, Any]:
    if not os.path.isfile(config_path):
        raise ServeDashboardError(f"Config file not found: {config_path}")
    try:
        with open(config_path, "r", encoding="utf-8") as f:
            raw = json.load(f)
    except (OSError, json.JSONDecodeError) as exc:
        raise ServeDashboardError(f"Failed to read/parse config file {config_path}: {exc}") from exc


    missing = [k for k in ("server_id", "report_dir") if k not in raw]
    if missing:
        raise ServeDashboardError(f"Config is missing required key(s) for this tool: {', '.join(missing)}")
    return raw




class DashboardRequestHandler(http.server.SimpleHTTPRequestHandler):
    """Serves *.html files out of `directory`, handles /api/* routes for
    config CRUD, disables directory listing, and redirects "/" to the
    configured index file."""


    index_name = "latest_dashboard.html"
    config_path = None  # Set by BoundHandler subclass


    def _clean_path(self) -> str:
        return self.path.split("?", 1)[0].split("#", 1)[0]


    # ------------------------------------------------------------------
    # JSON API helpers
    # ------------------------------------------------------------------


    def _send_json(self, data: Any, status: int = 200) -> None:
        """Send a JSON response with proper headers."""
        body = json.dumps(data, indent=2, sort_keys=True).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)


    def _send_error_json(self, status: int, message: str) -> None:
        self._send_json({"error": message}, status)


    def _read_body(self) -> Optional[bytes]:
        length = int(self.headers.get("Content-Length", 0))
        if length <= 0:
            return None
        return self.rfile.read(length)


    # ------------------------------------------------------------------
    # Config file operations
    # ------------------------------------------------------------------


    def _read_config_file(self) -> Optional[Dict[str, Any]]:
        """Read and parse the config file. Returns None if not found."""
        if not self.config_path or not os.path.isfile(self.config_path):
            return None
        with open(self.config_path, "r", encoding="utf-8") as f:
            return json.load(f)


    def _write_config_file(self, data: Dict[str, Any]) -> str:
        """Write config atomically, creating a timestamped backup first.
        Returns the backup path (empty string if no backup was created)."""
        backup_path = ""
        if os.path.isfile(self.config_path):
            ts = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
            backup_path = f"{self.config_path}.{ts}"
            shutil.copy2(self.config_path, backup_path)


        tmp = self.config_path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
            f.write("\n")
        os.replace(tmp, self.config_path)
        return backup_path


    def _validate_config(self, data: Any) -> list:
        """Validate a config dict. Returns a list of error messages (empty = valid)."""
        errors = []
        if not isinstance(data, dict):
            return ["Config must be a JSON object"]


        for key in ("server_id", "snapshot_dir", "report_dir"):
            if key not in data:
                errors.append(f"Missing required key: {key}")


        if "paths" not in data:
            errors.append("Missing required key: paths")
        elif not isinstance(data["paths"], list):
            errors.append("'paths' must be a list")
        else:
            for i, entry in enumerate(data["paths"]):
                if not isinstance(entry, dict) or "path" not in entry:
                    errors.append(f"paths[{i}]: must be an object with a 'path' key")
                elif not str(entry["path"]).startswith("/"):
                    errors.append(f"paths[{i}]: path must be absolute (start with /)")


        for key in ("snapshot_dir", "report_dir"):
            val = data.get(key)
            if val is not None and not str(val).startswith("/"):
                errors.append(f"'{key}' must be an absolute path")


        return errors


    # ------------------------------------------------------------------
    # API route dispatch
    # ------------------------------------------------------------------


    def _handle_api(self, method: str) -> None:
        """Route /api/* requests to the appropriate handler."""
        clean_path = self._clean_path()


        if not self.config_path:
            self._send_error_json(
                503,
                "No config file configured for this server instance. "
                "Start with --config to enable the config API.",
            )
            return


        if clean_path == "/api/config":
            if method == "GET":
                try:
                    config = self._read_config_file()
                    if config is None:
                        self._send_error_json(404, f"Config file not found: {self.config_path}")
                        return
                    self._send_json(config)
                except (OSError, json.JSONDecodeError) as exc:
                    self._send_error_json(500, f"Failed to read config: {exc}")
                return


            if method == "PUT":
                try:
                    body = self._read_body()
                    if not body:
                        self._send_error_json(400, "Request body is empty")
                        return
                    data = json.loads(body)
                    errors = self._validate_config(data)
                    if errors:
                        self._send_error_json(400, "; ".join(errors))
                        return
                    backup = self._write_config_file(data)
                    msg = "Configuration saved successfully"
                    if backup:
                        msg += f" (backup: {os.path.basename(backup)})"
                    self._send_json({"status": "ok", "message": msg})
                except json.JSONDecodeError:
                    self._send_error_json(400, "Invalid JSON in request body")
                except OSError as exc:
                    self._send_error_json(500, f"Failed to write config: {exc}")
                return


        self._send_error_json(404, f"Unknown API endpoint: {clean_path}")


    # ------------------------------------------------------------------
    # HTTP method handlers
    # ------------------------------------------------------------------


    def do_GET(self) -> None:  # noqa: N802 (stdlib naming convention)
        clean_path = self._clean_path()
        if clean_path.startswith("/api/"):
            self._handle_api("GET")
            return
        if clean_path in ("/", ""):
            self.send_response(302)
            self.send_header("Location", "/" + self.index_name)
            self.end_headers()
            return
        if not clean_path.endswith(".html"):
            self.send_error(404, "Not Found")
            return
        super().do_GET()


    def do_PUT(self) -> None:  # noqa: N802
        clean_path = self._clean_path()
        if clean_path.startswith("/api/"):
            self._handle_api("PUT")
            return
        self.send_error(405, "Method Not Allowed")


    def do_POST(self) -> None:  # noqa: N802
        clean_path = self._clean_path()
        if clean_path.startswith("/api/"):
            self._handle_api("POST")
            return
        self.send_error(405, "Method Not Allowed")


    def do_DELETE(self) -> None:  # noqa: N802
        clean_path = self._clean_path()
        if clean_path.startswith("/api/"):
            self._handle_api("DELETE")
            return
        self.send_error(405, "Method Not Allowed")


    def do_HEAD(self) -> None:  # noqa: N802
        clean_path = self._clean_path()
        if not clean_path.endswith(".html") and clean_path not in ("/", "") and not clean_path.startswith("/api/"):
            self.send_error(404, "Not Found")
            return
        super().do_HEAD()


    def list_directory(self, path):  # type: ignore[override]
        self.send_error(403, "Directory listing disabled")
        return None


def run_server(directory: str, host: str, port: int, index_name: str, config_path: str = None) -> int:
    class BoundHandler(DashboardRequestHandler):
        pass


    BoundHandler.index_name = index_name
    BoundHandler.config_path = config_path


    try:
        httpd = http.server.ThreadingHTTPServer(
            (host, port),
            functools.partial(BoundHandler, directory=directory),
        )
    except OSError as exc:
        raise ServeDashboardError(f"Failed to bind {host}:{port}: {exc}") from exc


    def _shutdown(signum, _frame):
        print(f"Received signal {signum}, shutting down...", flush=True)
        threading.Thread(target=httpd.shutdown, daemon=True).start()


    signal.signal(signal.SIGTERM, _shutdown)
    signal.signal(signal.SIGINT, _shutdown)


    display_host = host if host != "0.0.0.0" else "<this-server-ip>"
    print(f"serve_dashboard {SCRIPT_VERSION} - serving {directory}", flush=True)
    print(f"Listening on {host}:{port}", flush=True)
    print(f"URL: http://{display_host}:{port}/  (redirects to {index_name})", flush=True)
    if config_path:
        print(f"Config API enabled: {config_path}", flush=True)
    else:
        print("Config API disabled (no --config provided)", flush=True)
    if host == "127.0.0.1":
        print(
            "Bound to localhost only. For remote access use an SSH tunnel:\n"
            f"  ssh -L {port}:127.0.0.1:{port} user@<this-server>",
            flush=True,
        )


    try:
        httpd.serve_forever(poll_interval=0.5)
    finally:
        httpd.server_close()
        print("Server stopped.", flush=True)
    return 0


def main(argv: Optional[list] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Serve visualize_report.py HTML dashboards over HTTP.",
    )
    parser.add_argument("--config", help=f"Path to config.json (default lookup: {DEFAULT_CONFIG_PATH})")
    parser.add_argument("--dir", help="Directory to serve (overrides config.json); should be the dashboard/ subfolder written by visualize_report.py")
    parser.add_argument("--server-id", help="Server ID, used to derive the default index filename (overrides config.json)")
    parser.add_argument("--index", help="Override the filename '/' redirects to (default: latest_dashboard_<server_id>.html)")
    parser.add_argument("--host", default=None, help="Bind address (default: dashboard.host in config.json, else 127.0.0.1 - localhost only; see security warning in module docstring before using 0.0.0.0 or a real IP)")
    parser.add_argument("--port", type=int, default=None, help="Bind port (default: dashboard.port in config.json, else 8080)")
    parser.add_argument("--version", action="version", version=f"serve_dashboard {SCRIPT_VERSION}")
    args = parser.parse_args(argv)


    try:
        serve_dir = args.dir
        server_id = args.server_id
        dashboard_cfg: Dict[str, Any] = {}
        config_path = args.config


        if not serve_dir or not server_id or args.host is None or args.port is None:
            config_path = config_path or DEFAULT_CONFIG_PATH
            config = load_minimal_config(config_path)
            server_id = server_id or config["server_id"]
            serve_dir = serve_dir or os.path.join(config["report_dir"], "dashboard")
            dashboard_cfg = config.get("dashboard") or {}


        if not os.path.isdir(serve_dir):
            raise ServeDashboardError(
                f"Directory not found: {serve_dir} (run visualize_report.py at least once first)"
            )


        index_name = args.index or f"latest_dashboard_{server_id}.html"
        host = args.host or dashboard_cfg.get("host") or "127.0.0.1"
        port = args.port or dashboard_cfg.get("port") or 8080


        return run_server(
            os.path.abspath(serve_dir), host, int(port), index_name,
            config_path=config_path,
        )


    except ServeDashboardError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 2
    except KeyboardInterrupt:
        return 0


if __name__ == "__main__":
    sys.exit(main())
